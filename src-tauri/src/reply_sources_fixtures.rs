fn expected() -> Value {
    let cases: Vec<Value> = INPUTS
        .iter()
        .map(|input| {
            let split = split_sources(input).map(|(answer, sources)| {
                json!({
                    "answer": answer,
                    "sources": sources
                        .into_iter()
                        .map(|s| json!({ "url": s.url, "site": s.site }))
                        .collect::<Vec<_>>(),
                })
            });
            json!({ "input": input, "split": split })
        })
        .collect();
    json!({
        "about": "Generated by src-tauri/src/reply_sources_fixtures.rs from grokhub_core::reply_sources. Rerun it with UPDATE_FIXTURES=1; do not edit by hand.",
        "cases": cases,
    })
}

#[test]
fn ui_reply_sources_fixtures_match_the_core_split() {
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../ui/src/replySources.fixtures.json");
    let want = expected();
    if std::env::var_os("UPDATE_FIXTURES").is_some() {
        let text = serde_json::to_string_pretty(&want).expect("fixtures serialize");
        std::fs::write(&path, text + "\n").expect("write fixtures");
        return;
    }
    let have: Value = serde_json::from_str(&std::fs::read_to_string(&path).expect("read fixtures"))
        .expect("fixtures parse");
    assert!(
        have == want,
        "{} is out of date with grokhub_core::reply_sources; rerun with UPDATE_FIXTURES=1",
        path.display()
    );
}
